# 기존 2-도메인 체계와의 호환 매핑.
# `agents/analysis_agent.py` → `state["domain"]` → `judgment_agent.verified`가 아직
# 2-도메인을 전제하므로, 새 유형 라벨에서 옛 도메인을 파생시켜 파이프라인을 유지한다.
# 새 코드는 `domain`이 아니라 `articles`를 봐야 한다.
_LEGACY_DOMAIN: dict[str, str] = {
    "제7조": "책임제한_조항",   # 면책조항의 금지
    "제8조": "책임제한_조항",   # 손해배상액의 예정
    "제9조": "해지_조항",       # 계약의 해제·해지
}
LEGACY_DOMAINS = ("해지_조항", "책임제한_조항", "기타_조항", "해당없음")

_ART_PAT = __import__("re").compile(r"약관[^,;]{0,20}?법(?:률)?\s*제\s*(\d+)\s*조")


def normalize(raw: str) -> str | None:
    """FTC 의결서의 `근거_법령` 문자열에서 약관규제법 조 번호만 뽑는다.

    `"약관의 규제에 관한 법률 제6조 제2항 제1호"` → `"제6조"`.
    민법·상법 등 다른 법률의 조문(`"민법 제544조"`)과, 이 taxonomy 범위(6~14조)를
    벗어난 조문(제2조 정의, 제17조 등)은 `None`을 돌려 걸러낸다.
    """
    m = _ART_PAT.search(raw or "")
    if not m:
        return None
    art = f"제{int(m.group(1))}조"
    return art if art in ARTICLES else None


def derive_domain(articles: list[str] | None) -> str:
    """새 유형 라벨 → 옛 2-도메인. 호환 목적으로만 쓴다."""
    for a in articles or []:
        if a in _LEGACY_DOMAIN:
            return _LEGACY_DOMAIN[a]
    return "기타_조항" if articles else "해당없음"


def prompt_block() -> str:
    """LLM 프롬프트에 그대로 넣을 유형 목록. 각 호까지 포함해야 판정 일관성이 유지된다."""
    out = []
    for art, spec in ARTICLES.items():
        out.append(f'- {art} ({spec["title"]})')
        for it in spec["items"]:
            out.append(f"    {it}")
    return "\n".join(out)
